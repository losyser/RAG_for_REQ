# scripts/113_s3_expert_numbers.py
"""把 S3 配对 50 条外部盲评结果转成论文宏与表格。

只读 revision_artifacts/s3_paired_review50_20261019/review_results/reviewer1_first_pass.json
（由冻结的 analyze.py 逻辑经 run_reviewer1.py 生成）。不调用模型，不改统计口径。
RAG 错误的成因分类是作者对评审备注的编码（ERROR_CAUSE），随结果一并发布。

输出 data/search_results/exp_v4/s3_expert/s3_numbers.json；
--paper-dir 时写 s3_numbers.tex（宏）与 table_s3_expert.tex。
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
S3 = ROOT / "revision_artifacts/s3_paired_review50_20261019"
RES = S3 / "review_results/reviewer1_first_pass.json"
OUT = ROOT / "data/search_results/exp_v4/s3_expert"
LABELS = {"正确": "Correct", "可接受": "Acceptable", "错误": "Wrong", "无法判断": "Unknown"}
APPL = {"适用": "Appl", "不适用": "NotAppl", "工况不明": "CondUnknown"}

# 作者按评审备注对 RAG 错误条目的成因编码
ERROR_CAUSE = {
    "K849074": "table",     # 表格连字符被读成负号，得出 -100 °C
    "K204711": "table",     # 同上
    "K189805": "binding",   # 排气公差被归为冷却水指标
    "K997682": "binding",   # 空冷器入口设定点与增压器出口报警混用
    "K814606": "generation",  # "approx. 0.5 bar" 写成 "<= 0.5 bar"
    "K445671": "generation",  # 持续条件误读，主题漂移
}


def numbers(res: dict) -> dict:
    rv = res["reviewers"][0]
    rows, summ = rv["raw_ratings"], rv["summary"]
    m: dict = {}
    for arm, tag in (("rag", "Rag"), ("norag", "NoRag")):
        rs = [r for r in rows if r["arm"] == arm]
        c = Counter(r["correctness"] for r in rs)
        a = Counter(r["applicability"] for r in rs)
        m[f"SThree{tag}N"] = len(rs)
        for zh, en in LABELS.items():
            m[f"SThree{tag}{en}"] = c.get(zh, 0)
        for zh, en in APPL.items():
            m[f"SThree{tag}{en}"] = a.get(zh, 0)
        m[f"SThree{tag}CorrAppl"] = summ["primary"]["item_descriptive"][arm]["confirmed_success_count"]
        m[f"SThree{tag}NoDocBasis"] = sum(str(r["basis"] or "").startswith("工程依据") for r in rs)
        m[f"SThree{tag}ConfThree"] = sum(str(r["confidence"]) == "3" for r in rs)
        m[f"SThree{tag}SrcRate"] = summ["primary"]["source_equal_confirmed_success"][arm]
        m[f"SThree{tag}SrcRateSec"] = summ["secondary"]["source_equal_confirmed_success"][arm]
    p, s = summ["primary"], summ["secondary"]
    m.update({
        "SThreeSources": p["source_count"], "SThreeItems": len(rows),
        "SThreeDiff": p["source_equal_difference"],
        "SThreeBootLo": p["source_bootstrap_percentile_interval"][0],
        "SThreeBootHi": p["source_bootstrap_percentile_interval"][1],
        "SThreeBoundLo": p["unknown_assignment_bounds"][0], "SThreeBoundHi": p["unknown_assignment_bounds"][1],
        "SThreeSignPos": p["sign_test"]["positive_sources"], "SThreeSignNeg": p["sign_test"]["negative_sources"],
        "SThreeSignTies": p["sign_test"]["ties"], "SThreeSignP": p["sign_test"]["two_sided_p"],
        "SThreeDiffSec": s["source_equal_difference"],
        "SThreeBootLoSec": s["source_bootstrap_percentile_interval"][0],
        "SThreeBootHiSec": s["source_bootstrap_percentile_interval"][1],
    })
    rag_wrong = {r["blind_id"] for r in rows if r["arm"] == "rag" and r["correctness"] == "错误"}
    if rag_wrong != set(ERROR_CAUSE):
        raise SystemExit(f"error-cause coding out of date: {sorted(rag_wrong ^ set(ERROR_CAUSE))}")
    cause = Counter(ERROR_CAUSE.values())
    m.update({"SThreeErrTable": cause["table"], "SThreeErrBinding": cause["binding"], "SThreeErrGen": cause["generation"]})
    return m


def fmt(k: str, v) -> str:
    """Floats rounded half-up; signed and negative values in math mode for a true minus sign."""
    from decimal import ROUND_HALF_UP, Decimal
    if not isinstance(v, float):
        return str(v)
    d = Decimal(str(v)).quantize(Decimal("0.001" if k == "SThreeSignP" else "0.01"), ROUND_HALF_UP)
    s = f"{d:+}" if k.startswith(("SThreeDiff", "SThreeBound")) else f"{d}"
    return f"\\ensuremath{{{s}}}" if s.startswith(("+", "-")) else s


def to_tex(m: dict) -> str:
    lines = ["% generated by scripts/113_s3_expert_numbers.py -- do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{fmt(k, v)}}}" for k, v in m.items()]
    return "\n".join(lines) + "\n"


TABLE = r"""\begin{table}[htbp]
\caption{Blind expert review of paired numeric candidates: \SThreeSources{} source requirements for
which both arms produced numeric criteria, \SThreeRagN{} cited RAG candidates (Grades~A/B) and
\SThreeNoRagN{} uncited no-RAG candidates (Grade~X), one external marine-engineering reviewer.
Source-level rates weight each source requirement equally.  \emph{Correct} is the value
judgement alone; \emph{correct and applicable} additionally requires the stated conditions to
match the requirement, so the two counts differ by design.\label{tab:s3expert}}
\begin{tabularx}{\linewidth}{X c c}
\toprule
\textbf{Judgement} & \textbf{RAG} & \textbf{no-RAG} \\
\midrule
Correct & \SThreeRagCorrect & \SThreeNoRagCorrect \\
Acceptable & \SThreeRagAcceptable & \SThreeNoRagAcceptable \\
Wrong & \SThreeRagWrong & \SThreeNoRagWrong \\
Cannot judge & \SThreeRagUnknown & \SThreeNoRagUnknown \\
\midrule
Correct and applicable (items) & \SThreeRagCorrAppl & \SThreeNoRagCorrAppl \\
Source-level rate, correct and applicable & \SThreeRagSrcRate & \SThreeNoRagSrcRate \\
Source-level rate, incl.\ acceptable & \SThreeRagSrcRateSec & \SThreeNoRagSrcRateSec \\
No source document located by reviewer & \SThreeRagNoDocBasis & \SThreeNoRagNoDocBasis \\
\bottomrule
\end{tabularx}
\par\smallskip
{\footnotesize Primary difference (RAG $-$ no-RAG, correct and applicable): \SThreeDiff{}, source
bootstrap 95\% interval [\SThreeBootLo, \SThreeBootHi]; \SThreeSignPos{} sources favour RAG,
\SThreeSignNeg{} no-RAG, \SThreeSignTies{} tied (exact sign test $p=\SThreeSignP$). Assigning every
\emph{cannot judge} or unknown-condition item adversely or favourably bounds the difference within
[\SThreeBoundLo, \SThreeBoundHi]. Including \emph{acceptable}: \SThreeDiffSec{}
[\SThreeBootLoSec, \SThreeBootHiSec].\par}
\end{table}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper-dir", type=Path)
    a = ap.parse_args()
    res = json.loads(RES.read_text(encoding="utf-8"))
    m = numbers(res)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "s3_numbers.json").write_text(json.dumps({"macros": m, "error_cause": ERROR_CAUSE,
                                                    "protocol_deviations": res.get("protocol_deviations")},
                                                   ensure_ascii=False, indent=2), encoding="utf-8")
    if a.paper_dir:
        (a.paper_dir / "s3_numbers.tex").write_text(to_tex(m), encoding="utf-8")
        (a.paper_dir / "table_s3_expert.tex").write_text(TABLE, encoding="utf-8")
    print(json.dumps(m, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
