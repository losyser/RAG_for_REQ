# scripts/115_kappa_numbers.py
"""Paper macros for the blind taxonomy-label review (R1-4.2) and taxonomy/KB label facts.

Reads revision_artifacts/kappa_taxonomy_review_20261020/review_results/reviewer1.json
(frozen analyze.py output on the reviewer's first, independent submission) and the audited KB.
--paper-dir writes kappa_numbers.tex.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from cooling_rag_mg.evidence_taxonomy import COMPONENTS, INTENTS, TAXONOMY, all_pairs, valid_pair  # noqa: E402

RES = ROOT / "revision_artifacts/kappa_taxonomy_review_20261020/review_results/reviewer1.json"
KB = ROOT / "data/processed/evidence_units_v3_audited.jsonl"
OUT = ROOT / "data/search_results/exp_v4/kappa"


def r2(x: float) -> str:
    return str(Decimal(str(x)).quantize(Decimal("0.01"), ROUND_HALF_UP))


def pct(x: float) -> str:
    return str(Decimal(str(100 * x)).quantize(Decimal("1"), ROUND_HALF_UP)) + r"\%"


def numbers() -> dict:
    res = json.loads(RES.read_text(encoding="utf-8"))
    s, raw = res["summary"], res["raw"]
    units = [json.loads(l) for l in KB.open(encoding="utf-8")]
    used = {i for v in TAXONOMY.values() for i in v}
    outside = [u for u in units if not valid_pair(u["primary_component"], u["primary_intent"])]
    top = Counter((u["primary_component"], u["primary_intent"]) for u in outside).most_common(1)[0]
    comp_dis = [x for x in raw if x["author_component"] != x["rev_comp"]]
    m = {
        "KapN": s["n"],
        "KapCompAgree": pct(s["component"]["agreement"]), "KapComp": r2(s["component"]["kappa"]),
        "KapCompLo": r2(s["component"]["kappa_ci95"][0]), "KapCompHi": r2(s["component"]["kappa_ci95"][1]),
        "KapAspAgree": pct(s["aspect"]["agreement"]), "KapAsp": r2(s["aspect"]["kappa"]),
        "KapAspLo": r2(s["aspect"]["kappa_ci95"][0]), "KapAspHi": r2(s["aspect"]["kappa_ci95"][1]),
        "KapPairAgree": pct(s["pair"]["agreement"]),
        "KapCompDis": len(comp_dis),
        "KapCompDisSys": sum("cooling_system" in (x["author_component"], x["rev_comp"]) for x in comp_dis),
        "KapRevSys": sum(x["rev_comp"] == "cooling_system" for x in raw),
        "KapRevOutside": sum(not valid_pair(x["rev_comp"], x["rev_int"]) for x in raw),
        "KapTierLone": s["by_tier"].get("L1", {}).get("n", 0), "KapTierLtwo": s["by_tier"].get("L2", {}).get("n", 0),
        "KapTierLthree": s["by_tier"].get("L3", {}).get("n", 0),
        "TaxGeneralAspects": len(INTENTS), "TaxSpecificAspects": len(used - set(INTENTS)),
        "TaxAllAspects": len(used | set(INTENTS)), "TaxComponents": len(COMPONENTS), "TaxPairs": len(all_pairs()),
        "TaxPairsSpecific": sum(i not in INTENTS for _, i in all_pairs()),
        "KBOutsidePairs": len(outside), "KBOutsideTop": top[1],
    }
    return m


def main() -> None:
    ap = argparse.ArgumentParser(); ap.add_argument("--paper-dir", type=Path); a = ap.parse_args()
    m = numbers()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "kappa_numbers.json").write_text(json.dumps(m, ensure_ascii=False, indent=2), encoding="utf-8")
    if a.paper_dir:
        lines = ["% generated by scripts/115_kappa_numbers.py -- do not edit by hand"]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
        (a.paper_dir / "kappa_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(m, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
