# -*- coding: utf-8 -*-
"""
Generate a 30-requirement stress-test pool using Qwen (independent of DeepSeek).

Motivation: the original 100-requirement pool was generated by DeepSeek, the same
model family used for evaluation, creating a potential circular-dependency bias.
This script uses Qwen as an independent generator and injects seven realistic
deficiency patterns observed in actual ship engineering documents, producing
requirements that are harder and stylistically distinct from the dev pool.

Deficiency patterns injected:
  A  Vague-scope     — references "relevant regulations" without citing chapter/clause
  B  Multi-intent    — single sentence covers installation + parameter + alarm
  C  Implicit-cond   — applicable condition (load, season, mode) left unstated
  D  Cross-system    — couples cooling water to fuel-oil or lube-oil subsystems
  E  Qual-no-quant   — qualitative constraint with no numerical threshold
  F  Incomplete-ref  — cites "CCS rules" or "class requirements" without specifics
  G  Actor-ambiguous — unclear whether shipyard or equipment maker is responsible

Output: data/processed/stress_test_requirements.jsonl
Format: {"requirement_id": "ST001", "stakeholder": "...", "requirement_text": "..."}

Usage:
  export QWEN_API_KEY=sk-...          # or DASHSCOPE_API_KEY
  python scripts/37_generate_stress_test_requirements.py
  python scripts/37_generate_stress_test_requirements.py --model qwen-plus --dry-run
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

try:
    from openai import OpenAI
except ImportError:
    print("openai package required: pip install openai")
    sys.exit(1)

OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "stress_test_requirements.jsonl"

# ── 16 stakeholder types matching the dev pool ──────────────────────────────
STAKEHOLDERS = [
    "船东代表",
    "主机厂家",
    "系统设计方",
    "船厂建造方",
    "设备采购方",
    "轮机长",
    "自动化工程师",
    "安全负责人",
    "维修人员",
    "调试人员",
    "船级社验船师",
    "材料工程师",
    "运维管理人员",
    "船厂质量检验人员",
    "环保负责人",
    "项目管理方",
]

# 30 assignments: 14 stakeholders × 2 + 2 stakeholders × 1
ASSIGNMENTS: list[tuple[str, str]] = []
for s in STAKEHOLDERS[:14]:
    ASSIGNMENTS.append((s, "AB"))   # patterns injected per pair
    ASSIGNMENTS.append((s, "CDFG"))
for s in STAKEHOLDERS[14:]:
    ASSIGNMENTS.append((s, "EF"))

# ── Prompt templates ─────────────────────────────────────────────────────────

SYSTEM_PROMPT = """\
你是一名有经验的船舶项目协调员，负责收集各方利益相关者对"船舶主机冷却水系统"的原始需求。
你的任务是按照给定的利益相关方身份和缺陷模式，写出真实工程项目中常见的原始需求文本。

背景知识：主机冷却水系统包含高温淡水冷却回路（HT）、低温淡水冷却回路（LT）、海水冷却回路、
膨胀水箱、冷却泵、中央冷却器（板式热交换器）、温控阀、管路及自动化仪表等。

写作要求：
1. 完全用中文，语气符合该利益相关方的角色（船东关注经济性/可靠性，验船师关注法规合规，轮机长关注操作性）。
2. 每条需求是一段话（1–3句），不要分条列举，不要加标题。
3. 严格注入指定的缺陷模式（见下方说明），使需求带有真实工程文档的典型不完整性。
4. 不要替利益相关方"补全"需求——保留模糊、隐含、不完整的表达，这正是需要检索系统去解析的内容。

缺陷模式说明：
  A 范围模糊    — 引用"相关规定"、"行业惯例"、"厂家要求"，但不注明具体来源
  B 多意图混合  — 单句同时涉及安装、参数限值、报警联锁等多个工程方面
  C 条件隐含    — 未明确适用工况（如"满负荷"、"热带航区"、"靠港期间"）
  D 跨系统耦合  — 提到与燃油系统、滑油系统或其他系统的接口，但接口边界不清
  E 定性无定量  — 使用"适当"、"足够"、"不得过高"等表述，缺少具体数值
  F 规范引用不完整 — 提到"CCS规范"、"入级要求"或"船级社规则"但未注明章节号
  G 责任主体模糊 — 不清楚该条需求由船厂、设备厂商还是船东负责落实
"""


def _user_prompt(stakeholder: str, patterns: str, index: int) -> str:
    pattern_names = {
        "A": "范围模糊(A)",
        "B": "多意图混合(B)",
        "C": "条件隐含(C)",
        "D": "跨系统耦合(D)",
        "E": "定性无定量(E)",
        "F": "规范引用不完整(F)",
        "G": "责任主体模糊(G)",
    }
    active = "、".join(pattern_names[p] for p in patterns if p in pattern_names)
    return (
        f"请以【{stakeholder}】的身份，写1条关于船舶主机冷却水系统的原始需求。\n"
        f"必须同时体现以下缺陷模式：{active}。\n"
        f"只输出需求正文，不要加任何前缀、编号或解释。"
    )


# ── API call ─────────────────────────────────────────────────────────────────

def _get_client(model: str) -> tuple[OpenAI, str]:
    api_key = os.getenv("QWEN_API_KEY") or os.getenv("DASHSCOPE_API_KEY")
    if not api_key:
        raise EnvironmentError(
            "Set QWEN_API_KEY or DASHSCOPE_API_KEY before running this script."
        )
    client = OpenAI(
        api_key=api_key,
        base_url="https://dashscope.aliyuncs.com/compatible-mode/v1",
    )
    return client, model


def _call(client: OpenAI, model: str, stakeholder: str, patterns: str, idx: int) -> str:
    resp = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": _user_prompt(stakeholder, patterns, idx)},
        ],
        temperature=0.85,
        max_tokens=300,
    )
    return resp.choices[0].message.content.strip()


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate stress-test requirements via Qwen")
    parser.add_argument("--model", default="qwen-max", help="Qwen model name (default: qwen-max)")
    parser.add_argument("--dry-run", action="store_true", help="Print prompts without calling API")
    parser.add_argument("--output", default=str(OUTPUT_PATH), help="Output JSONL path")
    args = parser.parse_args()

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if args.dry_run:
        print("=== DRY RUN — prompts only ===\n")
        for i, (stakeholder, patterns) in enumerate(ASSIGNMENTS, 1):
            req_id = f"ST{i:03d}"
            print(f"[{req_id}] 利益相关方: {stakeholder}  模式: {patterns}")
            print(_user_prompt(stakeholder, patterns, i))
            print()
        return

    client, model = _get_client(args.model)
    results: list[dict] = []

    print(f"Generating {len(ASSIGNMENTS)} stress-test requirements with {model}...\n")
    for i, (stakeholder, patterns) in enumerate(ASSIGNMENTS, 1):
        req_id = f"ST{i:03d}"
        # Use ASCII-only progress to avoid Windows cmd encoding issues
        print(f"[{req_id}] patterns={patterns} ... ", end="", flush=True)
        try:
            text = _call(client, model, stakeholder, patterns, i)
            results.append({
                "requirement_id": req_id,
                "stakeholder": stakeholder,
                "requirement_text": text,
                "stress_patterns": list(patterns),
            })
            print("OK")
        except Exception as exc:
            print(f"FAILED: {exc}")
            results.append({
                "requirement_id": req_id,
                "stakeholder": stakeholder,
                "requirement_text": "",
                "stress_patterns": list(patterns),
                "error": str(exc),
            })
        time.sleep(0.5)

    with open(output_path, "w", encoding="utf-8") as f:
        for r in results:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    success = sum(1 for r in results if r.get("requirement_text"))
    print(f"\nSaved {success}/{len(results)} requirements -> {output_path}")


if __name__ == "__main__":
    main()
